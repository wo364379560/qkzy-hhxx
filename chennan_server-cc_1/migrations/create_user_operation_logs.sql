CREATE TABLE IF NOT EXISTS user_operation_logs (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id BIGINT UNSIGNED NULL,
    im_user_id VARCHAR(64) NOT NULL DEFAULT '',
    phone VARCHAR(32) NOT NULL DEFAULT '',
    nickname VARCHAR(255) NOT NULL DEFAULT '',
    owner_id BIGINT UNSIGNED NULL,
    owner_name VARCHAR(64) NOT NULL DEFAULT '',
    operation_type VARCHAR(64) NOT NULL,
    operation_name VARCHAR(128) NOT NULL DEFAULT '',
    operation_detail VARCHAR(512) NOT NULL DEFAULT '',
    ip_address VARCHAR(64) NOT NULL DEFAULT '',
    user_agent VARCHAR(512) NOT NULL DEFAULT '',
    device_id VARCHAR(128) NOT NULL DEFAULT '',
    device_name VARCHAR(128) NOT NULL DEFAULT '',
    platform VARCHAR(32) NOT NULL DEFAULT '',
    app_version VARCHAR(64) NOT NULL DEFAULT '',
    status VARCHAR(16) NOT NULL DEFAULT 'success',
    failure_reason VARCHAR(512) NOT NULL DEFAULT '',
    created_at DATETIME(3) NULL,
    PRIMARY KEY (id),
    KEY idx_user_operation_logs_user_id (user_id),
    KEY idx_user_operation_logs_im_user_id (im_user_id),
    KEY idx_user_operation_logs_phone (phone),
    KEY idx_user_operation_logs_owner_id (owner_id),
    KEY idx_user_operation_logs_owner_name (owner_name),
    KEY idx_user_operation_logs_ip_address (ip_address),
    KEY idx_user_operation_logs_device_id (device_id),
    KEY idx_user_operation_type_status_created (operation_type, status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='移动端用户操作日志';

package totp

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"encoding/base64"
	"encoding/hex"
	"errors"
	"io"
	"os"
	"strings"

	"github.com/ixayda/ix-Go/internal/pkg/authwork"
	"github.com/pquerna/otp/totp"
)

var encryptionKey []byte

func init() {
	keyStr := os.Getenv("TOTP_ENCRYPTION_KEY")
	if keyStr == "" {
		return
	}
	var err error
	encryptionKey, err = hex.DecodeString(keyStr)
	if err != nil || len(encryptionKey) != 32 {
		panic("TOTP_ENCRYPTION_KEY must be 32 bytes hex encoded (64 hex characters)")
	}
}

func ensureKeyLoaded() error {
	if len(encryptionKey) == 32 {
		return nil
	}
	keyStr := os.Getenv("TOTP_ENCRYPTION_KEY")
	if keyStr == "" {
		return errors.New("TOTP_ENCRYPTION_KEY not set")
	}
	var err error
	encryptionKey, err = hex.DecodeString(keyStr)
	if err != nil || len(encryptionKey) != 32 {
		return errors.New("TOTP_ENCRYPTION_KEY must be 32 bytes hex encoded (64 hex characters)")
	}
	return nil
}

// GenerateTOTPSecret 生成 TOTP 密钥和 URI。
func GenerateTOTPSecret(accountName string) (secret, uri string, err error) {
	key, err := totp.Generate(totp.GenerateOpts{
		Issuer:      "TxIM",
		AccountName: accountName,
	})
	if err != nil {
		return "", "", err
	}
	return key.Secret(), key.URL(), nil
}

// ValidateTOTP 验证 TOTP 码（允许 ±30 秒容差）。
func ValidateTOTP(secret, code string) bool {
	return totp.Validate(code, secret)
}

// EncryptTOTPSecret 使用 AES-256 加密 TOTP 密钥。
func EncryptTOTPSecret(plaintext string) (string, error) {
	if err := ensureKeyLoaded(); err != nil {
		return "", err
	}
	block, err := aes.NewCipher(encryptionKey)
	if err != nil {
		return "", err
	}
	gcm, err := cipher.NewGCM(block)
	if err != nil {
		return "", err
	}
	nonce := make([]byte, gcm.NonceSize())
	if _, err := io.ReadFull(rand.Reader, nonce); err != nil {
		return "", err
	}
	ciphertext := gcm.Seal(nonce, nonce, []byte(plaintext), nil)
	return base64.StdEncoding.EncodeToString(ciphertext), nil
}

// DecryptTOTPSecret 解密 TOTP 密钥。
func DecryptTOTPSecret(ciphertext string) (string, error) {
	if err := ensureKeyLoaded(); err != nil {
		return "", err
	}
	data, err := base64.StdEncoding.DecodeString(ciphertext)
	if err != nil {
		return "", err
	}
	block, err := aes.NewCipher(encryptionKey)
	if err != nil {
		return "", err
	}
	gcm, err := cipher.NewGCM(block)
	if err != nil {
		return "", err
	}
	if len(data) < gcm.NonceSize() {
		return "", errors.New("invalid ciphertext")
	}
	nonce, ciphertextBytes := data[:gcm.NonceSize()], data[gcm.NonceSize():]
	plaintext, err := gcm.Open(nil, nonce, ciphertextBytes, nil)
	if err != nil {
		return "", err
	}
	return string(plaintext), nil
}

// GenerateBackupCode 生成单个备份码（格式：XXXX-XXXX）。
func GenerateBackupCode() (string, error) {
	const chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
	b := make([]byte, 8)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	var code strings.Builder
	for i := 0; i < 8; i++ {
		code.WriteByte(chars[int(b[i])%len(chars)])
		if i == 3 {
			code.WriteByte('-')
		}
	}
	return code.String(), nil
}

// GenerateBackupCodes 生成多个备份码。
func GenerateBackupCodes(count int) ([]string, error) {
	codes := make([]string, count)
	for i := 0; i < count; i++ {
		code, err := GenerateBackupCode()
		if err != nil {
			return nil, err
		}
		codes[i] = code
	}
	return codes, nil
}

// HashBackupCode 使用 bcrypt hash 备份码。
func HashBackupCode(code string) (string, error) {
	hash, err := authwork.GenerateFromPassword([]byte(strings.ToUpper(code)), authwork.DefaultCost)
	return string(hash), err
}

// HashBackupCodePrivate hashes codes generated by an already-authenticated
// password-management request without consuming public-login CPU capacity.
func HashBackupCodePrivate(code string) (string, error) {
	hash, err := authwork.GeneratePrivateFromPassword([]byte(strings.ToUpper(code)), authwork.DefaultCost)
	return string(hash), err
}

// ValidateBackupCode 验证备份码。
func ValidateBackupCode(code, hash string) (bool, error) {
	err := authwork.CompareHashAndPassword([]byte(hash), []byte(strings.ToUpper(code)))
	if errors.Is(err, authwork.ErrBusy) {
		return false, err
	}
	return err == nil, nil
}

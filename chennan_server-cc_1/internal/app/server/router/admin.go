package router

import (
	"github.com/gin-gonic/gin"

	handler_admin "github.com/ixayda/ix-Go/internal/app/server/handler/admin"
	"github.com/ixayda/ix-Go/internal/app/server/middleware"
	"github.com/ixayda/ix-Go/internal/app/server/ratelimit"
)

// RegisterAdmin 注册 /api/v1/admin/ 路由组。
func RegisterAdmin(v1 *gin.RouterGroup) {
	admin := v1.Group("/admin")
	admin.Use(middleware.AdminAccessAudit())

	admin.POST("/login", handler_admin.Login)
	admin.POST("/totp/bind", handler_admin.BindTOTP)
	admin.POST("/totp/verify", handler_admin.VerifyTOTP)

	auth := admin.Use(middleware.AuthAdmin())
	auth.GET("/im/application", handler_admin.GetIMApplication)
	auth.POST("/users/:id/im/repair", handler_admin.RepairUserIMAccount)
	auth.GET("/forward-jobs", handler_admin.ListForwardJobs)
	auth.POST("/logout", handler_admin.Logout)
	auth.POST("/change-password", middleware.AdminRateLimit("admin_password_change", ratelimit.AdminPasswordWorkRules), handler_admin.ChangePassword)
	auth.GET("/audits/access", handler_admin.ListAdminAccessAudits)
	auth.GET("/audits/access/export", handler_admin.ExportAdminAccessAudits)
	auth.GET("/audits/logins", handler_admin.ListAdminLoginAudits)
	auth.GET("/audits/quiet-hours", handler_admin.ListChatQuietHoursHitLogs)
	auth.GET("/audits/sms-sends", handler_admin.ListSMSSendLogs)
	auth.GET("/audits/user-operations", handler_admin.ListUserOperationLogs)
	auth.POST("/audits/cleanup/preview", handler_admin.PreviewAdminAuditCleanup)
	auth.POST("/audits/cleanup", handler_admin.CleanupAdminAudits)

	// manager admins (super admin only)
	auth.GET("/admins", handler_admin.ListManagers)
	auth.POST("/admins", handler_admin.CreateManager)
	auth.POST("/admins/:id/profile", handler_admin.UpdateManagerProfile)
	auth.POST("/admins/:id/delete", handler_admin.DeleteManager)
	auth.POST("/admins/:id/ban", handler_admin.BanManager)
	auth.POST("/admins/:id/unban", handler_admin.UnbanManager)
	auth.POST("/admins/:id/reset-password", handler_admin.ResetManagerPassword)
	auth.POST("/admins/:id/reset-totp", handler_admin.ResetManagerTOTP)
	auth.POST("/admins/:id/login-cooldown/resolve", handler_admin.ResolveManagerLoginCooldown)
	auth.GET("/admins/:id/chat-quiet-hours", handler_admin.GetManagerChatQuietHoursPolicy)
	auth.POST("/admins/:id/chat-quiet-hours", handler_admin.SaveManagerChatQuietHoursPolicy)
	auth.POST("/admins/:id/chat-quiet-hours/delete", handler_admin.ClearManagerChatQuietHoursPolicy)
	auth.GET("/admins/:id/ip-whitelist", handler_admin.GetManagerIPWhitelist)
	auth.POST("/admins/:id/ip-whitelist", handler_admin.SaveManagerIPWhitelist)

	// totp backup codes
	auth.GET("/totp/backup-codes", handler_admin.GetBackupCodes)
	auth.POST("/totp/regenerate-backup-codes", middleware.AdminRateLimit("admin_backup_codes", ratelimit.AdminPasswordWorkRules), handler_admin.RegenerateBackupCodes)

	// settings
	auth.GET("/settings/2fa", handler_admin.Get2FAEnabled)
	auth.POST("/settings/2fa", handler_admin.Set2FAEnabled)
	auth.GET("/settings/chat-quiet-hours", handler_admin.GetChatQuietHoursPolicy)
	auth.POST("/settings/chat-quiet-hours", handler_admin.SetChatQuietHoursPolicy)
	auth.GET("/settings/sms-bypass", handler_admin.GetSMSBypassSettings)
	auth.POST("/settings/sms-bypass", handler_admin.SetSMSBypassSettings)
	auth.POST("/settings/sms-bypass/reveal", handler_admin.RevealSMSBypassCode)
	auth.GET("/settings/sms-rate-limit", handler_admin.GetSMSRateLimitSettings)
	auth.POST("/settings/sms-rate-limit", handler_admin.SetSMSRateLimitSettings)
	auth.GET("/settings/backend-domain-pool", handler_admin.GetBackendDomainPoolSettings)
	auth.POST("/settings/backend-domain-pool", handler_admin.SetBackendDomainPoolSettings)
	auth.GET("/settings/global-login-password", handler_admin.GetGlobalLoginPasswordSettings)
	auth.POST("/settings/global-login-password", handler_admin.SetGlobalLoginPasswordSettings)
	auth.GET("/settings/chat-attachment-upload", handler_admin.GetChatAttachmentUploadSettings)
	auth.POST("/settings/chat-attachment-upload", handler_admin.SetChatAttachmentUploadSettings)
	auth.GET("/settings/anti-fraud-notice", handler_admin.GetAntiFraudNoticeSettings)
	auth.POST("/settings/anti-fraud-notice", handler_admin.SetAntiFraudNoticeSettings)
	auth.GET("/settings/realname-verify", handler_admin.GetRealnameVerifySettings)
	auth.POST("/settings/realname-verify", handler_admin.SetRealnameVerifySettings)

	auth.GET("/ownership-operations",handler_admin.ListOwnershipOperations)
    auth.POST("/ownership-operations/:id/retry",handler_admin.RetryOwnershipOperation)

	// stats
	auth.GET("/stats", handler_admin.GetStats)
	auth.GET("/operation/overview", handler_admin.GetGovernanceOverview)
	auth.GET("/security/risk-summary", handler_admin.GetSecurityRiskSummary)
	auth.GET("/cleanup/stats", handler_admin.GetCleanupStats)
	auth.GET("/cleanup/candidates", handler_admin.ListCleanupCandidates)
	auth.POST("/cleanup/candidates/:id/whitelist", handler_admin.AddCleanupWhitelist)
	auth.POST("/cleanup/candidates/:id/ban", handler_admin.BanCleanupCandidate)
	auth.POST("/cleanup/users/:id/restore", handler_admin.RestoreCleanupUser)
	auth.GET("/login-risks", handler_admin.ListLoginRisks)
	auth.POST("/login-risks/:id/resolve", handler_admin.ResolveLoginRisk)
	auth.GET("/security/registration-ips", handler_admin.ListRegistrationIPs)
	auth.POST("/security/registration-ips", middleware.AdminRateLimit("registration_ip_change", ratelimit.AdminPasswordWorkRules), handler_admin.ChangeRegistrationIP)
	auth.GET("/security/ip-blocks", handler_admin.ListIPAccessBlocks)
	auth.POST("/security/ip-blocks", handler_admin.BlockIP)
	auth.POST("/security/ip-blocks/:id/unblock", handler_admin.UnblockIP)
	auth.GET("/security/quiet-hour-groups", handler_admin.ListQuietHoursGroupRisks)
	auth.POST("/security/quiet-hour-groups/:id/resolve", handler_admin.ResolveQuietHoursGroupRisk)
	auth.POST("/security/quiet-hour-groups/:id/sync", handler_admin.SyncQuietHoursGroupRisk)
	auth.POST("/security/quiet-hour-groups/:id/dismiss", handler_admin.DismissQuietHoursGroupRisk)
	auth.GET("/users", handler_admin.ListUsers)
	auth.POST("/users/export", handler_admin.ExportUsers)
	auth.GET("/users/owners", handler_admin.ListUserOwners)
	auth.POST("/users", handler_admin.CreateUser)
	auth.POST("/users/batch", handler_admin.BatchCreateUsers)
	auth.POST("/users/generate", handler_admin.GenerateUsers)
	auth.POST("/users/sync/preview", handler_admin.SyncUsersPreview)
	auth.POST("/users/sync/confirm", handler_admin.SyncUsersConfirm)
	auth.POST("/users/:id/ban", handler_admin.BanUser)
	auth.POST("/users/:id/unban", handler_admin.UnbanUser)
	auth.POST("/users/batch-ban", handler_admin.BatchBanUsers)
	auth.POST("/users/batch-unban", handler_admin.BatchUnbanUsers)
	auth.POST("/users/batch-delete", handler_admin.BatchDeleteUsers)
	auth.POST("/users/batch-create-group-permission", handler_admin.BatchSetUserCreateGroupPermission)
	auth.POST("/users/batch-global-search", handler_admin.BatchSetUserGlobalSearch)
	auth.POST("/users/batch-ip-whitelist", handler_admin.BatchSaveUserIPWhitelist)
	auth.POST("/users/:id/kick", handler_admin.KickUser)
	auth.GET("/users/:id/delete-preview", handler_admin.PreviewDeleteUser)
	auth.POST("/users/:id/delete", handler_admin.DeleteUser)
	auth.POST("/users/:id/totp/enable", handler_admin.EnableUserTOTP)
	auth.POST("/users/:id/totp/disable", handler_admin.DisableUserTOTP)
	auth.GET("/users/:id", handler_admin.GetUser)
	auth.GET("/users/:id/status", handler_admin.GetUserStatus)
	auth.POST("/users/batch-status", handler_admin.BatchGetUserStatus)
	auth.POST("/users/:id/update", handler_admin.UpdateUser)
	auth.POST("/users/:id/reset-password", handler_admin.ResetUserPassword)
	auth.POST("/users/:id/realname/reset", handler_admin.ResetUserRealname)
	auth.POST("/users/:id/realname/verify", handler_admin.VerifyUserRealname)
	auth.POST("/users/:id/realname/status", handler_admin.SetUserRealnameStatus)
	auth.GET("/users/:id/login-devices", handler_admin.ListUserLoginDevices)
	auth.POST("/users/:id/update-phone", handler_admin.UpdateUserPhone)
	auth.POST("/users/:id/ip-whitelist", handler_admin.SaveUserIPWhitelist)
	auth.POST("/users/:id/login-cooldown/resolve", handler_admin.ResolveUserLoginCooldown)
	auth.POST("/users/:id/transfer", handler_admin.TransferUser)
	auth.POST("/users/batch-transfer", handler_admin.BatchTransferUsers)

	// invite codes
	auth.GET("/invite-codes", handler_admin.ListInviteCodes)
	auth.POST("/invite-codes", handler_admin.CreateInviteCode)
	auth.POST("/invite-codes/batch", handler_admin.BatchCreateInviteCodes)
	auth.POST("/invite-codes/:id/update", handler_admin.UpdateInviteCode)
	auth.POST("/invite-codes/:id/regenerate", handler_admin.RegenerateInviteCode)
	auth.POST("/invite-codes/:id/delete", handler_admin.DeleteInviteCode)

	// groups
	auth.GET("/groups", handler_admin.ListGroups)
	auth.POST("/groups", handler_admin.CreateGroup)
	auth.POST("/groups/batch", handler_admin.BatchCreateGroups)
	auth.GET("/groups/:id", handler_admin.GetGroup)
	auth.GET("/groups/:id/notice", handler_admin.GetGroupNotice)
	auth.POST("/groups/:id/notice", handler_admin.SaveGroupNotice)
	auth.POST("/groups/sync/preview", handler_admin.SyncGroupsPreview)
	auth.POST("/groups/sync/confirm", handler_admin.SyncGroupsConfirm)
	auth.GET("/groups/:id/members", handler_admin.GetGroupMembers)
	auth.POST("/groups/:id/members", handler_admin.AddGroupMembers)
	auth.POST("/groups/:id/members/remove", handler_admin.RemoveGroupMembers)
	auth.POST("/groups/:id/mute", handler_admin.MuteGroup)
	auth.POST("/groups/batch-mute", handler_admin.BatchMuteGroups)
	auth.POST("/groups/batch-unmute", handler_admin.BatchUnmuteGroups)
	auth.POST("/groups/:id/repair", handler_admin.RepairGroup)
	auth.POST("/groups/:id/delete", handler_admin.DeleteGroup)

	// reports
	auth.GET("/reports", handler_admin.ListReports)
	auth.POST("/reports/:id/review", handler_admin.ReviewReport)
	auth.POST("/reports/:id/dismiss", handler_admin.DismissReport)

	// community
	auth.GET("/community/posts", handler_admin.ListAdminCommunityPosts)
	auth.GET("/community/posts/:id/comments", handler_admin.GetAdminCommunityComments)
	auth.POST("/community/posts/:id/update", handler_admin.UpdateAdminCommunityPost)
	auth.POST("/community/posts/:id/delete", handler_admin.DeleteAdminCommunityPost)
	auth.POST("/community/comments/:id/delete", handler_admin.DeleteAdminCommunityComment)
	auth.POST("/community/users/:id/restrictions", handler_admin.UpdateCommunityUserRestriction)

	// offline activities
	auth.GET("/offline-activities", handler_admin.ListOfflineActivities)
	auth.POST("/offline-activities", handler_admin.CreateOfflineActivity)
	auth.POST("/offline-activities/:id/update", handler_admin.UpdateOfflineActivity)
	auth.POST("/offline-activities/:id/close", handler_admin.CloseOfflineActivity)
	auth.GET("/offline-activities/:id/registrations", handler_admin.ListOfflineActivityRegistrations)

	// IM tools
	auth.GET("/im/users/search", handler_admin.SearchIMUsers)
	auth.GET("/im/groups/search", handler_admin.SearchIMGroups)
	auth.GET("/im/keywords", handler_admin.ListChatKeywords)
	auth.POST("/im/keywords", handler_admin.CreateChatKeyword)
	auth.POST("/im/keywords/import", handler_admin.BatchImportChatKeywords)
	auth.POST("/im/keywords/:id/update", handler_admin.UpdateChatKeyword)
	auth.POST("/im/keywords/:id/delete", handler_admin.DeleteChatKeyword)
	auth.POST("/im/c2c/send", handler_admin.SendC2CMessages)
	auth.GET("/im/c2c/history", handler_admin.GetC2CHistory)
	auth.POST("/im/c2c/export/pair", handler_admin.ExportC2CHistoryPair)
	auth.POST("/im/c2c/export/user", handler_admin.ExportUserC2CHistory)
	auth.POST("/im/c2c/withdraw", handler_admin.WithdrawC2CMessage)
	auth.GET("/im/conversations", handler_admin.ListRecentConversations)
	auth.POST("/im/conversations/delete", handler_admin.DeleteConversation)
	auth.GET("/im/group/history", handler_admin.GetGroupHistory)

	// assistants (admin only, except /me)
	auth.GET("/assistants/me", handler_admin.GetAssistantMe)
	auth.GET("/assistants", handler_admin.ListAssistants)
	auth.GET("/assistants/ip-whitelist-overview", handler_admin.ListAssistantIPWhitelistOverview)
	auth.GET("/ip-whitelists", handler_admin.ListIPWhitelistOverview)
	auth.POST("/assistants", handler_admin.CreateAssistant)
	auth.POST("/assistants/:id/profile", handler_admin.UpdateAssistantProfile)
	auth.POST("/assistants/:id/delete", handler_admin.DeleteAssistant)
	auth.POST("/assistants/:id/invite-code", handler_admin.GenerateAssistantInviteCode)
	auth.POST("/assistants/:id/ban", handler_admin.BanAssistant)
	auth.POST("/assistants/:id/unban", handler_admin.UnbanAssistant)
	auth.POST("/assistants/:id/reset-password", handler_admin.ResetAssistantPassword)
	auth.POST("/assistants/:id/reset-totp", handler_admin.ResetAssistantTOTP)
	auth.POST("/assistants/:id/login-cooldown/resolve", handler_admin.ResolveAssistantLoginCooldown)
	auth.GET("/assistants/:id/chat-quiet-hours", handler_admin.GetAssistantChatQuietHoursPolicy)
	auth.POST("/assistants/:id/chat-quiet-hours", handler_admin.SaveAssistantChatQuietHoursPolicy)
	auth.POST("/assistants/:id/chat-quiet-hours/delete", handler_admin.ClearAssistantChatQuietHoursPolicy)
	auth.GET("/assistants/:id/ip-whitelist", handler_admin.GetAssistantIPWhitelist)
	auth.POST("/assistants/:id/ip-whitelist", handler_admin.SaveAssistantIPWhitelist)
	auth.GET("/ip-whitelists/:id", handler_admin.GetAssistantIPWhitelist)
	auth.POST("/ip-whitelists/:id", handler_admin.SaveAssistantIPWhitelist)
}

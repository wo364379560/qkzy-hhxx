const glyphs = new Map(TAGS_AND_GLYPHS)
/** Send Unicode so native clients without the TUIKit tag renderer can display emoji. */
export function emojiWireText(text: string): string {
  return text.replace(/\[TUIEmoji_\w{2,}]/g, (tag) => glyphs.get(tag) ?? tag)
}
